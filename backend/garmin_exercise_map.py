def garmin_exercise(prose: str):
    """Return (category, exerciseName) for a plan-prose description. Falls back
    to (CORE, "") if nothing matches so at least the category name shows."""
    p = (prose or "").lower()
    for needle, hit in _EX_MAP:
        if needle in p:
            return hit
    return ("CORE", "")
